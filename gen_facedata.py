#!/usr/bin/env python3
# Render a photo to a fixed-width ASCII portrait and emit it as a NASM include
# (face_data.inc) so the kernel carries the face itself - the boot animation
# forms it locally, no network needed.
# Usage: python3 gen_facedata.py [image] [width]
import sys
import ascii_art

src = sys.argv[1] if len(sys.argv) > 1 else "dario.jpg"
W = int(sys.argv[2]) if len(sys.argv) > 2 else 36
lines = ascii_art.render(src, W, rows=50)
lines = [ln.ljust(W)[:W] for ln in lines]           # exact width, no terminators
H = len(lines)
COL = 80 - W - 2                                     # right-aligned (dialogue on the left)

with open("face_data.inc", "w", encoding="ascii") as f:
    f.write("; generated by gen_facedata.py from %s\n" % src)
    f.write("FACE_W   equ %d\n" % W)
    f.write("FACE_H   equ %d\n" % H)
    f.write("FACE_COL equ %d\n" % COL)
    f.write("face_data:\n")
    for ln in lines:
        assert '"' not in ln and "\\" not in ln, "unsafe char in art"
        f.write('    db "%s"\n' % ln)
print("face_data.inc: %dx%d, col %d" % (W, H, COL))
